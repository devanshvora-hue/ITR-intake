"""PDF statement extraction (Stage 5.7) with the local xpdf `pdftotext`.

Every PDF here is generated by `synthetic_pdf.py`; no real statement is used.
If the extractor is missing, these tests are skipped and that must be
reported (the upload tests separately cover the 'extractor unavailable' path).
"""

import pytest

import synthetic_pdf as sp
from itr_intake import statement_import as si
from itr_intake_server import statements

PDFTOTEXT = statements.find_pdftotext()
pytestmark = pytest.mark.skipif(PDFTOTEXT is None, reason="xpdf pdftotext is not available")
FY = "2025-26"

PAGE1 = [("01/04/2025", "UPI/100001/SYNTHETIC GROCER", "1,250.00", "", "48,750.00"),
         ("03/04/2025", "NEFT SALARY SYNTHETIC CO\nREF SYN0001", "", "85,000.00", "1,33,750.00"),
         ("04/04/2025", "UPI/100002/SYNTHETIC CAFE", "250.00", "", "1,33,500.00")]
PAGE2 = [("05/04/2025", "ATM WDL SYNTHETIC BRANCH", "5,000.00", "", "1,28,500.00"),
         ("07/04/2025", "INTEREST CREDIT SYNTHETIC", "", "12.35", "1,28,512.35")]


def extract(tmp_path, pages, *, compress=False):
    data = sp.build_pdf(pages, compress=compress)
    path = tmp_path / "s.pdf"
    path.write_bytes(data)
    texts = statements.extract_pdf_pages(PDFTOTEXT, path, tmp_path)
    return si.parse_pdf_pages(texts, financial_year=FY, contains_images=statements._contains_images(data)), texts


def good_pages():
    return [sp.statement_page(PAGE1, opening="50,000.00", page_no=1),
            sp.statement_page(PAGE2, closing="1,28,512.35", page_no=2)]


# === valid statements =======================================================================================

@pytest.mark.parametrize("compress", [False, True])
def test_a_multi_page_digital_statement_is_extracted(tmp_path, compress):
    r, texts = extract(tmp_path, good_pages(), compress=compress)
    assert len(texts) == 2 and r.pages_total == 2
    assert r.status == si.EXTRACTED, (r.review_reasons, r.page_warnings, r.rejected)
    assert [(t.date, t.debit, t.credit, t.balance) for t in r.transactions] == [
        ("01/04/2025", "1,250.00", None, "48,750.00"), ("03/04/2025", None, "85,000.00", "1,33,750.00"),
        ("04/04/2025", "250.00", None, "1,33,500.00"), ("05/04/2025", "5,000.00", None, "1,28,500.00"),
        ("07/04/2025", None, "12.35", "1,28,512.35")]
    assert r.transactions[1].narration == "NEFT SALARY SYNTHETIC CO REF SYN0001"  # wrapped line joined
    assert r.row_pages == {1: 1, 2: 1, 3: 1, 4: 2, 5: 2}
    assert r.summary_rows == 2  # opening and closing balance lines are not transactions


def test_carried_forward_lines_are_summaries(tmp_path):
    p1 = sp.statement_page(PAGE1, opening="50,000.00", page_no=1)
    p1.text(sp.COL_NARR, 120, "Balance C/F")
    p1.text(sp.COL_BAL_R - 11 * sp.CHAR_W, 120, "1,33,500.00")
    p2 = sp.statement_page(PAGE2, opening=None, page_no=2)
    p2.text(sp.COL_NARR, 120, "Balance B/F")
    p2.text(sp.COL_BAL_R - 11 * sp.CHAR_W, 120, "1,33,500.00")
    r, _ = extract(tmp_path, [p1, p2])
    assert len(r.transactions) == 5 and r.summary_rows >= 3 and r.status == si.EXTRACTED, r.review_reasons


def test_alternative_column_labels(tmp_path):
    page = sp.statement_page(PAGE1, opening="50,000.00",
                             labels=("Txn Date", "Description", "Debit", "Credit", "Balance"))
    r, _ = extract(tmp_path, [page])
    assert r.status == si.EXTRACTED and len(r.transactions) == 3


# === incomplete or unsupported content ============================================================================

def test_a_blank_page_is_flagged(tmp_path):
    p1, p2 = good_pages()
    r, _ = extract(tmp_path, [p1, sp.blank_page(), p2])
    assert r.status == si.MANUAL_REVIEW and len(r.transactions) == 5
    assert si.PageWarning(2, "no_extractable_text") in r.page_warnings and "pages_without_text" in r.review_reasons


def test_an_image_only_pdf_produces_no_transactions(tmp_path):
    r, _ = extract(tmp_path, [sp.image_only_page(), sp.image_only_page()])
    assert r.transactions == () and r.status == si.MANUAL_REVIEW
    assert {w.page for w in r.page_warnings if w.code == "no_extractable_text"} == {1, 2}
    assert {"pages_without_text", "image_content_not_extracted", "unsupported_layout",
            "no_transactions_found"} <= set(r.review_reasons)


def test_a_mixed_statement_keeps_good_pages_and_flags_the_rest(tmp_path):
    p1, _ = good_pages()
    r, _ = extract(tmp_path, [p1, sp.mixed_page(), sp.image_only_page()])
    assert r.status == si.MANUAL_REVIEW and len(r.transactions) == 3  # page 1 kept, never called complete
    pages = {(w.page, w.code) for w in r.page_warnings}
    assert (2, "no_transactions_on_page") in pages and (3, "no_extractable_text") in pages
    assert "image_content_not_extracted" in r.review_reasons


def test_an_unsupported_layout_is_not_guessed(tmp_path):
    page = sp.Page()
    page.text(40, 500, "SYNTHETIC BANK STATEMENT")
    page.text(40, 480, "Date        Details                         Amount        Dr/Cr")
    page.text(40, 460, "01/04/2025  UPI SYNTHETIC SHOP              1,250.00      Dr")
    page.text(40, 440, "02/04/2025  NEFT SYNTHETIC SALARY          85,000.00      Cr")
    r, _ = extract(tmp_path, [page])
    assert r.transactions == () and r.status == si.MANUAL_REVIEW and "unsupported_layout" in r.review_reasons


def gap_page(balance: str):
    """Row 2's amount is drawn in the gap after the Withdrawals label and
    before the Deposits label, i.e. inside the Withdrawals band."""
    page = sp.statement_page(PAGE1[:1], opening="50,000.00")
    page.text(sp.COL_DATE, 300, "02/04/2025")
    page.text(sp.COL_NARR, 300, "SYNTHETIC GAP AMOUNT")
    page.text(572, 300, "999.00")
    page.text(sp.COL_BAL_R - len(balance) * sp.CHAR_W, 300, balance)
    return page


def test_a_gap_amount_is_read_by_band_and_must_satisfy_the_balance_chain(tmp_path):
    # Start-anchored bands read it as a withdrawal; the balance confirms that.
    r, _ = extract(tmp_path, [gap_page("47,751.00")])
    assert r.status == si.EXTRACTED and r.transactions[1].debit == "999.00" and r.transactions[1].credit is None


def test_a_gap_amount_that_was_really_a_deposit_is_never_extracted(tmp_path):
    # Same position, but the balance shows a deposit: the band reading is wrong,
    # the balance chain breaks, and the statement goes to manual review.
    r, _ = extract(tmp_path, [gap_page("49,749.00")])
    assert r.status == si.MANUAL_REVIEW and "balance_chain_broken" in r.review_reasons


def test_a_missing_row_breaks_the_balance_chain(tmp_path):
    rows = [PAGE1[0], PAGE1[2]]  # the salary credit is missing from the extracted text
    r, _ = extract(tmp_path, [sp.statement_page(rows, opening="50,000.00")])
    assert r.status == si.MANUAL_REVIEW and "balance_chain_broken" in r.review_reasons


def test_rows_without_balances_cannot_be_confirmed(tmp_path):
    rows = [(d, n, dr, cr, "") for d, n, dr, cr, _ in PAGE1]
    r, _ = extract(tmp_path, [sp.statement_page(rows)])
    assert r.status == si.MANUAL_REVIEW and "balance_column_missing" in r.review_reasons


def test_invalid_dates_and_amounts_are_rejected_rows(tmp_path):
    rows = [PAGE1[0], ("32/04/2025", "SYNTHETIC BAD DATE", "10.00", "", "48,740.00")]
    r, _ = extract(tmp_path, [sp.statement_page(rows, opening="50,000.00")])
    assert r.status == si.MANUAL_REVIEW
    assert [(x.row_number, x.codes, x.page) for x in r.rejected] == [(2, ("invalid_date",), 1)]


def test_an_unrecognised_amount_line_is_flagged(tmp_path):
    page = sp.statement_page(PAGE1, opening="50,000.00")
    page.text(sp.COL_NARR, 200, "SOMETHING UNEXPLAINED")
    page.text(sp.COL_BAL_R - 8 * sp.CHAR_W, 200, "1,000.00")
    r, _ = extract(tmp_path, [page])
    assert r.status == si.MANUAL_REVIEW and si.PageWarning(1, "unrecognised_amount_line") in r.page_warnings
    assert len(r.transactions) == 3  # the stray amount did not become a transaction


def test_a_page_without_a_table_before_any_header_is_flagged(tmp_path):
    cover = sp.Page().text(40, 500, "SYNTHETIC BANK - STATEMENT OF ACCOUNT - COVER PAGE WITH NO TABLE AT ALL")
    p1, p2 = good_pages()
    r, _ = extract(tmp_path, [cover, p1, p2])
    assert si.PageWarning(1, "no_transaction_table") in r.page_warnings and r.status == si.MANUAL_REVIEW
    assert len(r.transactions) == 5


def test_no_pages_is_rejected():
    assert si.parse_pdf_pages([]).status == si.REJECTED


# === malformed files =============================================================================================

@pytest.mark.parametrize("data", [b"%PDF-1.4\nthis is not a pdf at all\n%%EOF\n",
                                  b"%PDF-1.4\n" + bytes(range(256)) * 20 + b"\n%%EOF\n"])
def test_malformed_pdfs_fail_safely(tmp_path, data):
    path = tmp_path / "bad.pdf"
    path.write_bytes(data)
    try:
        texts = statements.extract_pdf_pages(PDFTOTEXT, path, tmp_path)
    except statements.ExtractionFailed as exc:
        assert exc.code in ("pdf_unreadable",)
        return
    r = si.parse_pdf_pages(texts, financial_year=FY)
    assert r.transactions == () and r.status in (si.MANUAL_REVIEW, si.REJECTED)


def test_a_truncated_pdf_is_rejected_before_extraction():
    data = sp.build_pdf(good_pages())
    assert statements.check_upload(data[: len(data) // 2], "s.pdf", "application/pdf") == ("pdf", "truncated_pdf")


def test_extraction_leaves_no_text_files_behind(tmp_path):
    extract(tmp_path, good_pages())
    assert sorted(p.name for p in tmp_path.iterdir()) == ["s.pdf"]
